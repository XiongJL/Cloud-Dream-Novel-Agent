import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import ts from 'typescript';
const compile = source => ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
const asUrl = source => `data:text/javascript;base64,${Buffer.from(compile(source)).toString('base64')}`;
const registry = asUrl(await readFile(new URL('../electron/backup/BackupRegistry.ts', import.meta.url), 'utf8'));
const gate = asUrl((await readFile(new URL('../electron/backup/MaintenanceGate.ts', import.meta.url), 'utf8')).replace("'./BackupRegistry'", JSON.stringify(registry)));
const { dataOperation, exclusiveData, sealDataMaintenance, isDataMaintenance } = await import(gate);
let release;
const pending = new Promise(resolve => { release = resolve; });
let writes = 0;
const writer = dataOperation(async () => { await pending; await dataOperation(async () => { writes++; }); });
const snapshot = exclusiveData(async () => { assert.equal(writes, 1, 'snapshot must wait for the entire active writer'); });
assert.equal(isDataMaintenance(), true);
await assert.rejects(dataOperation(async () => { writes++; }), error => error.code === 'BUSY');
release();
await Promise.all([writer, snapshot]);
let lateResult;
const result = new Promise(resolve => { lateResult = resolve; });
await dataOperation(async () => { setTimeout(() => { void dataOperation(async () => { writes++; }).then(() => lateResult('wrote'), error => lateResult(error.code)); }, 0); });
await exclusiveData(async () => { assert.equal(await result, 'BUSY', 'a detached callback cannot inherit permission from a finished writer'); });
assert.equal(writes, 1);
sealDataMaintenance();
await assert.rejects(dataOperation(async () => { writes++; }), error => error.code === 'BUSY');
console.log('Backup maintenance passed: writer draining, new request blocking, detached callback sealing and permanent seal after activation.');
