import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import ts from 'typescript';

const source = await readFile(new URL('../shared/agentSkillCatalogCache.ts', import.meta.url), 'utf8');
const output = ts.transpileModule(source, {compilerOptions: {module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022}}).outputText;
const {AgentSkillCatalogCache} = await import(`data:text/javascript;base64,${Buffer.from(output).toString('base64')}`);
let time = 0, calls = 0;
const cache = new AgentSkillCatalogCache(10_000, () => time);
const fetch = async () => { calls += 1; return {title: 'A', error: ''}; };
const concurrent = await Promise.all([cache.load('a', fetch), cache.load('a', fetch), cache.load('a', fetch)]);
assert.equal(calls, 1);
assert.equal(concurrent[0], concurrent[2]);
assert.equal((await cache.load('a', fetch)).title, 'A');
assert.equal(calls, 1);
time = 10_001;
await cache.load('a', fetch);
assert.equal(calls, 2);
await cache.load('b', fetch);
assert.equal(calls, 3);
cache.invalidate('a');
await cache.load('a', fetch);
assert.equal(calls, 4);

let release;
const old = cache.load('pending', () => new Promise(resolve => {release = resolve;}));
await Promise.resolve();
cache.invalidate('pending');
await cache.load('pending', async () => 'fresh after scope mutation');
release('old');
await old;
assert.equal(cache.peek('pending'), 'fresh after scope mutation');
await assert.rejects(cache.load('failure', async () => {throw new Error('network');}), /network/);
assert.equal(await cache.load('failure', async () => 'retry works'), 'retry works');
await cache.load('partial', async () => ({error: 'pack failed'}), value => !value.error);
assert.equal(cache.peek('partial'), undefined);
assert.equal(await cache.load('partial', async () => 'retry partial'), 'retry partial');
cache.clear();
assert.equal(cache.peek('pending'), undefined);
assert.equal(cache.peek('failure'), undefined);
console.log('Skill catalog cache: concurrent deduplication, TTL, scope invalidation, key isolation and error retry passed.');
