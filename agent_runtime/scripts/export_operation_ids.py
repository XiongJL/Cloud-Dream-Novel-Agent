"""Export the registered operation contract used by Electron authoring validation."""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from novel_agent_runtime.intent.operations import INTENT_OPERATION_REGISTRY

target = Path(__file__).resolve().parents[2] / "apps/desktop/shared/agentOperationIds.ts"
ids = [item["id"] for item in INTENT_OPERATION_REGISTRY.list_public()]
target.write_text("// Generated by agent_runtime/scripts/export_operation_ids.py; registry parity is tested.\n"
    + "export const AGENT_OPERATION_IDS = [\n" + "".join(f"  '{item}',\n" for item in ids)
    + "] as const;\nexport const REGISTERED_AGENT_OPERATIONS: ReadonlySet<string> = new Set(AGENT_OPERATION_IDS);\n", encoding="utf-8")
